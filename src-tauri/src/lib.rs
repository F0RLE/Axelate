/// Exports Specta TypeScript bindings and normalizes generated whitespace.
pub fn export_typescript_bindings(
    builder: &Builder<tauri::Wry>,
    path: impl AsRef<Path>,
) -> Result<(), Box<dyn std::error::Error>> {
    let path = resolve_manifest_path(path.as_ref());
    builder.export(
        Typescript::default().header(TYPESCRIPT_BINDINGS_HEADER),
        &path,
    )?;
    strip_generated_trailing_whitespace(&path)?;
    Ok(())
}

fn resolve_manifest_path(path: &Path) -> PathBuf {
    if path.is_absolute() {
        return path.to_path_buf();
    }

    Path::new(env!("CARGO_MANIFEST_DIR")).join(path)
}

fn strip_generated_trailing_whitespace(path: &Path) -> Result<(), std::io::Error> {
    let source = std::fs::read_to_string(path)?;
    let mut normalized = source
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");

    if source.ends_with('\n') {
        normalized.push('\n');
    }

    if normalized != source {
        std::fs::write(path, normalized)?;
    }

    Ok(())
}

/// Registers all managed services into Tauri's DI container.
fn setup_dependencies(app: &tauri::App) -> Result<(), Box<dyn std::error::Error>> {
    crate::utils::paths::init_filesystem()?;

    let file_service: std::sync::Arc<dyn crate::domain::filesystem::service::FileService> =
        std::sync::Arc::new(LocalFileService::new());
    let json_store = JsonStore::new(std::sync::Arc::clone(&file_service));

    let settings_service = SettingsService::new(json_store.clone());
    let ui_state_service = UiStateService::new(json_store.clone());
    let window_settings_service = WindowSettingsService::new(json_store.clone());
    let settings_service_for_api = settings_service.clone();
    let ui_state_service_for_api = ui_state_service.clone();

    let config_repo = crate::infrastructure::config::config_repository::FileConfigRepository::new(
        app.handle().clone(),
    );
    let config_service = std::sync::Arc::new(
        crate::domain::system::config_service::ConfigService::new(Box::new(config_repo)),
    );

    app.manage(file_service);
    app.manage(json_store);
    app.manage(settings_service);
    app.manage(ui_state_service);
    app.manage(window_settings_service);
    app.manage(std::sync::Arc::clone(&config_service));
    app.manage(crate::domain::modules::downloader::DownloaderService::new());
    app.manage(crate::domain::modules::settings_ui_protocol::ModuleSettingsSessionStore::default());
    let sessions = std::sync::Arc::new(ChatSessionManager::new());
    sessions.start_saver();
    app.manage(std::sync::Arc::clone(&sessions));
    app.manage(ai::ChatCancellationRegistry::default());
    let image_generation_state = std::sync::Arc::new(ImageGenerationState::new());
    app.manage(std::sync::Arc::clone(&image_generation_state));
    let monitor_service = std::sync::Arc::new(SystemMonitorService::new());
    app.manage(std::sync::Arc::clone(&monitor_service));

    // Engine manager (local AI engine lifecycle)
    let tauri_emitter = std::sync::Arc::new(
        crate::infrastructure::engine::tauri_emitter::TauriEngineEmitter::new(
            app.handle().clone(),
            std::sync::Arc::clone(&image_generation_state),
        ),
    );
    let engine_manager = std::sync::Arc::new(EngineManager::new(tauri_emitter));

    // Load engine definitions from local_modules.json and register them
    {
        let local_modules: Vec<crate::models::config::ModuleItem> =
            serde_json::from_str(include_str!("../resources/config/local_modules.json"))
                .unwrap_or_else(|e| {
                    tracing::warn!("Failed to parse local_modules.json for engine registry: {e}");
                    Vec::new()
                });
        let defs = crate::domain::engine::registry::load_engine_definitions(&local_modules);
        let em = std::sync::Arc::clone(&engine_manager);
        tauri::async_runtime::block_on(async move {
            em.register_definitions(defs).await;
        });
    }

    app.manage(std::sync::Arc::clone(&engine_manager));

    let integration_api = crate::domain::integration_api::start_launcher_http_api(
        crate::domain::integration_api::LauncherHttpApiContext::new(
            app.handle().clone(),
            std::sync::Arc::clone(&sessions),
            std::sync::Arc::clone(&config_service),
            std::sync::Arc::clone(&engine_manager),
            std::sync::Arc::clone(&image_generation_state),
            settings_service_for_api,
            ui_state_service_for_api,
        ),
    )?;
    tracing::debug!(
        "Launcher integration API ready at {}",
        integration_api.base_url()
    );
    app.manage(integration_api);

    let monitor_emitter = std::sync::Arc::new(
        crate::infrastructure::monitoring::tauri_emitter::TauriMonitoringEmitter::new(
            app.handle().clone(),
        ),
    );
    monitor_service.start_monitoring(monitor_emitter, DEFAULT_MONITORING_INTERVAL_MS);
    crate::domain::modules::integration_watcher::start(app.handle().clone());

    #[cfg(desktop)]
    setup_global_shortcut(app)?;

    setup_system_tray(app)?;

    tracing::info!("Axelate is ready");
    Ok(())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
#[allow(unsafe_code, clippy::large_stack_frames, clippy::print_stderr)]
/// Main entry point for the Tauri application
pub fn run() {
    // 1. Environment validation (platform webview/runtime prerequisites)
    {
        use crate::domain::system::startup::EnvironmentValidator;
        use crate::infrastructure::system::startup::PlatformStartupInfrastructure;
        EnvironmentValidator::new(
            Box::new(PlatformStartupInfrastructure),
            crate::infrastructure::config::settings::get_language_sync(),
        )
        .validate();
    }

    // 2. Logging
    let log_guard = match logger::init_global_logger() {
        Ok(guard) => Some(guard),
        Err(e) => {
            eprintln!("Failed to initialize logger: {e}");
            None
        }
    };
    tracing::debug!("Initializing Axelate...");
    setup_webview2_cache();
    setup_webview2_debugging();

    // 3. Tauri builder + plugins
    let tauri_builder = tauri::Builder::default()
        .plugin(tauri_plugin_shell::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_fs::init())
        .plugin(tauri_plugin_clipboard_manager::init())
        .plugin(crate::domain::modules::settings_ui_protocol::init())
        .plugin(tauri_plugin_single_instance::init(|app, _args, _cwd| {
            if let Some(window) = app.get_webview_window("main") {
                show_and_focus_window(&window);
                #[cfg(target_os = "windows")]
                {
                    let _ = window.set_always_on_top(true);
                    std::thread::sleep(std::time::Duration::from_millis(100));
                    let _ = window.set_always_on_top(false);
                }
                if let Some(monitor) = app.try_state::<std::sync::Arc<SystemMonitorService>>() {
                    monitor.set_paused(false);
                }
            } else {
                create_main_window(app);
            }
            tracing::info!("Single instance: second launch detected.");
        }));

    // 4. Specta bindings (debug only)
    let builder = create_specta_builder();
    #[cfg(debug_assertions)]
    export_typescript_bindings(&builder, TYPESCRIPT_BINDINGS_PATH)
        .map_err(|e| tracing::error!("Failed to export typescript bindings: {e}"))
        .ok();

    // 5. Build & run
    match tauri_builder
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            setup_dependencies(app)?;
            if let Some(guard) = log_guard {
                app.manage(guard);
            }
            Ok(())
        })
        .on_window_event(|window, event| {
            if let tauri::WindowEvent::CloseRequested { .. } = event {
                if let Some(monitor) = window
                    .app_handle()
                    .try_state::<std::sync::Arc<SystemMonitorService>>()
                {
                    monitor.set_paused(true);
                }
                crate::utils::memory::trim_memory();
            }
        })
        .build(tauri::generate_context!())
    {
        Ok(app) => app.run(|app_handle, event| {
            if let tauri::RunEvent::ExitRequested { api, .. } = event {
                tracing::info!(
                    "RunEvent::ExitRequested. IS_QUITTING: {}",
                    IS_QUITTING.load(Ordering::Relaxed)
                );
                if IS_QUITTING.load(Ordering::Relaxed) {
                    tracing::info!("App Exiting...");
                    if let Some(sessions) =
                        app_handle.try_state::<std::sync::Arc<ChatSessionManager>>()
                        && let Err(error) = sessions.save_to_disk()
                    {
                        tracing::error!("Failed to save chat history during exit: {error:?}");
                    }
                    if let Some(am) = app_handle.try_state::<std::sync::Arc<EngineManager>>() {
                        tauri::async_runtime::block_on(async move {
                            let _ = am.stop().await;
                        });
                    }
                } else {
                    crate::utils::memory::trim_memory();
                    api.prevent_exit();
                }
            }
        }),
        Err(e) => {
            tracing::error!("Error building application: {e}");
            std::process::exit(1);
        }
    }
}
