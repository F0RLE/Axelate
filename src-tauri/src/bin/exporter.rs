//! Standalone utility to export TypeScript bindings for the Axelate project.

use axelate_lib::create_specta_builder;
use specta_typescript::Typescript;

fn main() {
    let builder = create_specta_builder();
    builder
        .export(
            Typescript::default()
                .header("/* eslint-disable */\n// This file was generated by [tauri-specta](https://github.com/oscartbeaumont/tauri-specta).\n// Do not edit this file manually, as it will be overwritten.\n"),
            "../src/shared/types/bindings.ts",
        )
        .expect("Failed to export typescript bindings");
    println!("Bindings exported successfully!");
}
