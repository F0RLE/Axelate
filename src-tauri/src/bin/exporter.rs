//! Standalone utility to export TypeScript bindings for the Axelate project.

use axelate_lib::create_specta_builder;
use specta_typescript::Typescript;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let builder = create_specta_builder();
    builder.export(
        Typescript::default().header("/* eslint-disable @typescript-eslint/no-explicit-any, @typescript-eslint/no-unused-vars, @typescript-eslint/ban-ts-comment */\n// This file was generated by [tauri-specta](https://github.com/oscartbeaumont/tauri-specta).\n// Do not edit this file manually, as it will be overwritten.\n"),
        "../src/shared/types/bindings.ts",
    )?;

    #[allow(clippy::print_stdout)]
    {
        println!("Bindings exported successfully!");
    }
    Ok(())
}
